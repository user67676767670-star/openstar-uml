/* Markdown documentation generator tests */
'use strict';
const OS = globalThis.OS;
const { makeDemoProject } = require('./helpers.js');

t.suite('markdown');

const { project } = makeDemoProject();
const md = OS.Markdown.generate(project);

t.ok(md.startsWith('# Untitled'), 'project title heading');
t.ok(md.includes('Generated by OpenStar UML'), 'generator stamp');
t.ok(md.includes('## Diagram Index'), 'diagram index section');
t.ok(md.includes('**Main** — Class Diagram'), 'diagram listed with type label');
t.ok(md.includes('### Class: Person') || md.includes('## Class: Person') || /#+ Class: Person/.test(md), 'class heading');
t.ok(md.includes('**Attributes**'), 'attributes section');
t.ok(/\| - \| id \| int \| 1 \| 0 \|/.test(md) || md.includes('| id |'), 'attribute table row');
t.ok(md.includes('getName()'), 'operation signature present');
t.ok(md.includes('**Relationships**') || md.includes('**Association**'), 'relationships documented');
t.ok(md.includes('Generalization'), 'generalization listed');
t.ok(/#+ Enumeration: Grade/.test(md), 'enumeration heading');
t.ok(md.includes('`A`') && md.includes('`B`'), 'enum literals');
t.ok(/#+ State Machine: OrderSM/.test(md), 'state machine heading');
t.ok(md.includes('entry/notify') || md.includes('entry / notify'), 'state entry activity');
t.ok(md.includes('pay [amount>0] / ship'), 'transition label in flows table');
t.ok(/#+ Actor: Customer/.test(md), 'actor heading');
t.ok(md.includes('Sample note text'), 'note documentation included');
t.ok(md.includes('order.war'), 'artifact listed');

// pipe escaping inside tables
{
  const p2 = new OS.Project();
  p2.newProject();
  const m = p2.firstModel();
  const c = p2.createElement(m, 'UMLClass', { name: 'A|B' });
  const a = OS.model.createElement(p2, 'UMLAttribute', { name: 'x|y', type: 'T' });
  OS.model.addOwned(p2, c, a, 'ownedAttributes');
  const md2 = OS.Markdown.generate(p2);
  t.ok(md2.includes('Class: A|B'), 'heading keeps raw name');
  t.ok(md2.includes('x\\|y'), 'pipes escaped in table cells');
}
